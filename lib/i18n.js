const DICT = { ru: {}, kk: KK }

export function getLang() {
  if (typeof window === 'undefined') return 'ru'
  try { return localStorage.getItem(KEY) === 'kk' ? 'kk' : 'ru' } catch { return 'ru' }
}

export function setLang(lang) {
  try { localStorage.setItem(KEY, lang) } catch {}
  try { document.documentElement.lang = lang === 'kk' ? 'kk' : 'ru' } catch {}
  window.dispatchEvent(new CustomEvent(EVENT, { detail: lang }))
}

export function translate(lang, text, vars) {
  let out = (DICT[lang] && DICT[lang][text]) || text
  if (vars) for (const [k, v] of Object.entries(vars)) out = out.split(`{${k}}`).join(String(v))
  return out
}

/** const { t, lang, setLang } = useT() */
export function useT() {
  const [lang, setL] = useState('ru')
  useEffect(() => {
    setL(getLang())
    const on = e => setL(e.detail === 'kk' ? 'kk' : 'ru')
    window.addEventListener(EVENT, on)
    return () => window.removeEventListener(EVENT, on)
  }, [])
  const t = useCallback((text, vars) => translate(lang, text, vars), [lang])
  return { t, lang, setLang, locale: lang === 'kk' ? 'kk-KZ' : 'ru-RU' }
}

/** Переключатель «Қаз / Рус». */
export function LangSwitch({ className = '' }) {
  const { lang } = useT()
  return (
    <div className={`inline-flex p-0.5 rounded-full bg-[var(--color-bg-soft)] text-[11px] font-semibold ${className}`} role="group" aria-label="Язык / Тіл">
      {[['ru', 'Рус'], ['kk', 'Қаз']].map(([k, l]) => (
        <button
          key={k}
          type="button"
          onClick={() => setLang(k)}
          aria-pressed={lang === k}
          className={`px-2.5 py-1 rounded-full transition-colors ${lang === k ? 'bg-[var(--color-bg-card)] text-[var(--color-text-primary)] shadow-sm' : 'text-[var(--color-text-tertiary)]'}`}
        >
          {l}
        </button>
      ))}
    </div>
  )
}
